const PRESET_MAP = new Map(PROVIDER_PRESETS.map((p) => [p.id, p]));

// Trims whitespace and trailing slashes; non-strings become ''.
export function normalizeBaseUrl(url) {
  if (typeof url !== 'string') return '';
  return url.trim().replace(/\/+$/, '');
}

export function getPreset(presetId) {
  return PRESET_MAP.get(presetId) ?? PRESET_MAP.get('custom');
}

export function createProviderFromPreset(presetId, overrides = {}) {
  const preset = getPreset(presetId);
  const provider = {
    id: preset.id === 'custom' ? `custom-${uid()}` : preset.id,
    presetId: preset.id,
    name: preset.name,
    protocol: preset.protocol,
    baseUrl: preset.baseUrl,
    apiKey: '',
    enabled: false,
    models: [...preset.defaultModels],
    defaultModel: preset.defaultModel,
    imageApi: preset.imageApi,
    imageModels: [...preset.defaultImageModels],
    defaultImageModel: preset.defaultImageModel,
    extraHeaders: { ...preset.extraHeaders },
    modelInfo: {},
    prices: {}, // user's own prices per model: { [modelId]: { input, output } } in USD per 1M tokens
    billing: { managementKey: '', teamId: '' }, // xAI: Management API access for the balance
  };
  if (overrides && typeof overrides === 'object') {
    for (const [key, value] of Object.entries(overrides)) {
      if (value !== undefined) provider[key] = deepClone(value);
    }
  }
  provider.presetId = preset.id;
  provider.baseUrl = normalizeBaseUrl(provider.baseUrl);
  return provider;
}

export function createCustomProvider({ name, baseUrl, protocol = 'openai', apiKey = '' } = {}) {
  const url = normalizeBaseUrl(baseUrl);
  return createProviderFromPreset('custom', {
    id: `custom-${uid()}`,
    name: typeof name === 'string' && name.trim() ? name.trim() : t('core.providers.custom.name'),
    protocol: protocol === 'anthropic' ? 'anthropic' : 'openai',
    baseUrl: url,
    apiKey: typeof apiKey === 'string' ? apiKey.trim() : '',
    // A freshly added custom endpoint is meant to be used right away.
    enabled: Boolean(url),
  });
}
